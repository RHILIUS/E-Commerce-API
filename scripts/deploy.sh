#!/usr/bin/env bash
# Operate a single Ubuntu backend host from a trusted workstation.
set -Eeuo pipefail
umask 077
if (( $# != 3 )) || [[ ! "$1" =~ ^(check|bootstrap|update|status)$ ]] || [[ "$2" != --env-file ]]; then
    echo 'Usage: bash scripts/deploy.sh check|bootstrap|update|status --env-file .env.deploy' >&2
    exit 2
fi
operation=$1
script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
for required in python3 ssh ssh-keygen tar curl; do command -v "$required" >/dev/null; done
payload=$(mktemp -d)
trap 'rm -rf -- "$payload"' EXIT
python3 "$script_dir/deployment/config.py" "$operation" "$3" "$payload"
# Generated by the strict parser, never sourced directly from user configuration.
# shellcheck source=/dev/null
source "$payload/local.conf"
ssh_options=(-T -i "$SSH_KEY_FILE" -o BatchMode=yes -o IdentitiesOnly=yes
    -o StrictHostKeyChecking=yes -o "UserKnownHostsFile=$SSH_KNOWN_HOSTS_FILE"
    -o ConnectTimeout=15 -o ServerAliveInterval=15 -o ServerAliveCountMax=3)
ssh-keygen -y -P '' -f "$SSH_KEY_FILE" >/dev/null
ssh-keygen -F "$DEPLOY_HOST" -f "$SSH_KNOWN_HOSTS_FILE" >/dev/null || {
    echo 'No verified server host key found in SSH_KNOWN_HOSTS_FILE.' >&2; exit 1;
}
cp "$script_dir/deployment/remote.sh" "$payload/remote.sh"
cp "$script_dir/deployment/renew-certificate.sh" "$payload/renew-certificate.sh"
# The remote command is constant; configuration and secrets travel over stdin.
tar -C "$payload" --exclude=local.conf -cf - . | ssh "${ssh_options[@]}" "$DEPLOY_USER@$DEPLOY_HOST" \
    'set -eu; umask 077; task_dir=$(mktemp -d); trap '\''rm -rf -- "$task_dir"'\'' EXIT; tar -xf - -C "$task_dir"; bash "$task_dir/remote.sh" "$task_dir"'
if [[ "$operation" == bootstrap || "$operation" == update ]]; then
    curl --fail --silent --show-error --connect-timeout 15 --max-time 45 \
        "https://$API_DOMAIN/api/schema/" -o /dev/null
    echo 'Public HTTPS schema request passed. Verify login, media, email and payment integrations separately.'
fi
